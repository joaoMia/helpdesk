CREATE TABLE "public"."project_requests" (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code integer GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
  requester_id uuid NOT NULL REFERENCES "public"."users"(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  title text NOT NULL CHECK (length(btrim(title)) BETWEEN 3 AND 160),
  objective text NOT NULL CHECK (length(btrim(objective)) BETWEEN 10 AND 4000),
  need text NOT NULL CHECK (length(btrim(need)) BETWEEN 10 AND 4000),
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX project_requests_requester_created_idx ON "public"."project_requests"(requester_id,created_at,id);
CREATE INDEX project_requests_created_idx ON "public"."project_requests"(created_at,id);
CREATE TABLE "public"."project_request_events" (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  project_id uuid NOT NULL REFERENCES "public"."project_requests"(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  actor_id uuid NOT NULL REFERENCES "public"."users"(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  type text NOT NULL CHECK (type='REQUESTED'),
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX project_request_events_project_created_idx ON "public"."project_request_events"(project_id,created_at,id);
CREATE TRIGGER immutable_project_requests BEFORE UPDATE OR DELETE ON "public"."project_requests"
FOR EACH ROW EXECUTE FUNCTION "public"."immutable_conversation_record"();
CREATE TRIGGER immutable_project_request_events BEFORE UPDATE OR DELETE ON "public"."project_request_events"
FOR EACH ROW EXECUTE FUNCTION "public"."immutable_conversation_record"();
